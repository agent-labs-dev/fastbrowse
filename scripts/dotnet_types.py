"""Write the .NET client's protocol types from `protocol/schema.json`.

    uv run --no-project python scripts/dotnet_types.py

Each model the client sends or reads becomes a record with `init` properties in `Fastbrowse.Protocol`, and each enum
a C# enum that System.Text.Json reads and writes by its wire value; the protocol version, the method names and the error
codes become constants in `ProtocolConstants`. The JSON-RPC envelopes are left out: the client writes those itself.
Standard library only.
"""

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA = REPO / "protocol" / "schema.json"
OUT = REPO / "dotnet" / "src" / "Fastbrowse" / "Protocol.g.cs"
SKIPPED = {
    "Error",
    "ErrorCode",
    "ErrorResponse",
    "JsonValue",
    "NoParams",
    "Notification",
    "Params",
    "Request",
    "RequestId",
    "Response",
    "ServerMethod",
    "ServerRequest",
}
RAW = {"JsonValue", "RequestId"}


def pascal(name: str) -> str:
    return "".join(word[:1].upper() + word[1:] for word in re.split(r"[_/-]", name) if word)


def summary(text: str, indent: str) -> str:
    text = text.strip().replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"`([^`]+)`", r"<c>\1</c>", text)
    lines = "".join(f"{indent}/// {line}".rstrip() + "\n" for line in text.split("\n"))
    return f"{indent}/// <summary>\n{lines}{indent}/// </summary>\n"


def cs_type(schema: dict) -> str:
    """The C# type a property reads into, without the `?` a null adds."""
    if "$ref" in schema:
        name = schema["$ref"].removeprefix("#/$defs/")
        return "JsonElement" if name in RAW else name
    if "anyOf" in schema:
        others = [branch for branch in schema["anyOf"] if branch.get("type") != "null"]
        return cs_type(others[0]) if len(others) == 1 else "JsonElement"
    kind = schema.get("type")
    if kind == "string":
        return "byte[]" if schema.get("format") == "base64" else "string"
    if kind in ("integer", "number", "boolean"):
        return {"integer": "long", "number": "double", "boolean": "bool"}[kind]
    if kind == "array":
        items = schema.get("prefixItems", [schema.get("items", {})])[0]
        return f"IReadOnlyList<{cs_type(items)}>"
    if kind == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict) and additional:
            return f"IReadOnlyDictionary<string, {cs_type(additional)}>"
    return "JsonElement"


def nullable(schema: dict) -> bool:
    return any(branch.get("type") == "null" for branch in schema.get("anyOf", []))


def record(name: str, schema: dict) -> str:
    required = set(schema.get("required", []))
    out = summary(schema["description"], "") if schema.get("description") else ""
    out += f"public sealed record {name}\n{{\n"
    for key, prop in schema.get("properties", {}).items():
        cs = cs_type(prop)
        # A field the wire may leave out, or may write as null, reads as null. So does a tag such as "type": "step",
        # which only the server writes, so a record built here need not name it.
        optional = nullable(prop) or key not in required or "const" in prop
        if prop.get("description"):
            out += summary(prop["description"], "    ")
        declared = f"{cs}? {pascal(key)}" if optional else f"required {cs} {pascal(key)}"
        out += f'    [JsonPropertyName("{key}")]\n    public {declared} {{ get; init; }}\n\n'
    return out.rstrip("\n") + "\n}\n\n"


def enum(name: str, schema: dict) -> str:
    out = summary(schema["description"], "") if schema.get("description") else ""
    out += f"[JsonConverter(typeof(JsonStringEnumConverter<{name}>))]\npublic enum {name}\n{{\n"
    out += "".join(f'    [JsonStringEnumMemberName("{value}")]\n    {pascal(value)},\n' for value in schema["enum"])
    return out + "}\n\n"


def constants(values: dict) -> str:
    out = "/// <summary>\n/// The values a client has to hold the same as the server.\n/// </summary>\n"
    out += "public static class ProtocolConstants\n{\n"
    out += "    /// <summary>The version of the wire format this client speaks.</summary>\n"
    out += f"    public const int Version = {values['PROTOCOL_VERSION']};\n\n"
    out += "".join(f'    public const string Method{pascal(m.lower())} = "{v}";\n' for m, v in values["Method"].items())
    out += "\n"
    out += "".join(
        f'    public const string ServerMethod{pascal(m.lower())} = "{v}";\n' for m, v in values["ServerMethod"].items()
    )
    out += "\n"
    out += "".join(f"    public const int Error{pascal(m.lower())} = {v};\n" for m, v in values["ErrorCode"].items())
    return out + "}\n"


def main() -> int:
    document = json.loads(SCHEMA.read_text(encoding="utf-8"))
    out = (
        "// Generated by scripts/dotnet_types.py from protocol/schema.json, which\n"
        "// crates/fastbrowse-core/src/protocol.rs writes. Do not edit: change the types there, then run the script.\n"
        "#nullable enable\n\nusing System.Collections.Generic;\nusing System.Text.Json;\n"
        "using System.Text.Json.Serialization;\n\nnamespace Fastbrowse.Protocol;\n\n"
    )
    for name, schema in sorted(document["$defs"].items()):
        if name in SKIPPED:
            continue
        out += enum(name, schema) if "enum" in schema else record(name, schema)
    out += constants(document["constants"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
