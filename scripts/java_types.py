"""Write the Java client's protocol types from `protocol/schema.json`.

    uv run --no-project python scripts/java_types.py

Each model the client sends or reads becomes a record in `dev.agentlabs.fastbrowse.protocol`, with a builder, and each
enum a Java enum; the protocol version, the method names and the error codes become constants in `Protocol`. The
JSON-RPC envelopes are left out: the client writes those itself. Standard library only.
"""

import json
import re
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA = REPO / "protocol" / "schema.json"
PACKAGE = "dev.agentlabs.fastbrowse.protocol"
OUT = REPO / "java" / "src" / "main" / "java" / Path(*PACKAGE.split("."))
BANNER = (
    "// Generated by scripts/java_types.py from protocol/schema.json, which crates/fastbrowse-core/src/protocol.rs\n"
    "// writes. Do not edit: change the types there, then run the script.\n"
)
# The envelopes and the definitions with no Java shape of their own: JSON-RPC is the client's, and the rest is raw JSON.
SKIPPED = {
    "Error",
    "ErrorCode",
    "ErrorResponse",
    "JsonValue",
    "NoParams",
    "Notification",
    "Params",
    "Request",
    "RequestId",
    "Response",
    "ServerMethod",
    "ServerRequest",
}
RAW = {"JsonValue", "RequestId"}
BOXED = {"long": "Long", "double": "Double", "boolean": "Boolean"}


def camel(name: str) -> str:
    head, *rest = re.split(r"[_/-]", name)
    return head + "".join(word[:1].upper() + word[1:] for word in rest)


def constant(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", value).upper()


def javadoc(text: str, indent: str) -> str:
    text = text.strip().replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;")
    text = (
        re.sub(r"`([^`]+)`", r"{@code \1}", text)
        .replace("@", "&#64;")
        .replace("{&#64;code", "{@code")
        .replace("&#64;param", "@param")
    )
    lines = [f"{indent} * {line}".rstrip() for line in text.split("\n")]
    return f"{indent}/**\n" + "\n".join(lines) + f"\n{indent} */\n"


class Generator:
    def __init__(self, defs: dict) -> None:
        self.defs = defs

    def java_type(self, schema: dict, required: bool) -> str:
        """The Java type a property reads into. A primitive only where the value is always there."""
        if "$ref" in schema:
            name = schema["$ref"].removeprefix("#/$defs/")
            return "JsonNode" if name in RAW else name
        if "anyOf" in schema:
            others = [branch for branch in schema["anyOf"] if branch.get("type") != "null"]
            if len(others) != 1:
                return "JsonNode"
            return self.boxed(self.java_type(others[0], False))
        kind = schema.get("type")
        if kind == "string":
            return "byte[]" if schema.get("format") == "base64" else "String"
        if kind in ("integer", "number", "boolean"):
            primitive = {"integer": "long", "number": "double", "boolean": "boolean"}[kind]
            return primitive if required else BOXED[primitive]
        if kind == "array":
            items = schema.get("prefixItems", [schema.get("items", {})])[0]
            return f"List<{self.boxed(self.java_type(items, False))}>"
        if kind == "object":
            additional = schema.get("additionalProperties")
            if isinstance(additional, dict) and additional:
                return f"Map<String, {self.boxed(self.java_type(additional, False))}>"
            return "JsonNode"
        return "JsonNode"

    @staticmethod
    def boxed(java: str) -> str:
        return BOXED.get(java, java)

    def record(self, name: str, schema: dict) -> str:
        required = set(schema.get("required", []))
        fields = [
            (key, camel(key), self.java_type(prop, key in required and prop.get("type") not in (None, "null")), prop)
            for key, prop in schema.get("properties", {}).items()
        ]
        out = [BANNER, f"package {PACKAGE};\n\n"]
        imports = ["com.fasterxml.jackson.annotation.JsonProperty"]
        body = " ".join(java for _, _, java, _ in fields)
        if "JsonNode" in body:
            imports.append("tools.jackson.databind.JsonNode")
        if "List<" in body:
            imports.append("java.util.List")
        if "Map<" in body:
            imports.append("java.util.Map")
        out += [f"import {each};\n" for each in sorted(imports)] + ["\n"]
        # A record component takes no doc comment of its own; its description is an @param of the record's.
        described = [(field, prop["description"]) for _, field, _, prop in fields if prop.get("description")]
        doc = schema.get("description", "")
        params = "\n".join(f"@param {field} " + text.replace("\n", " ") for field, text in described)
        if doc or params:
            out.append(javadoc(doc + ("\n\n" if doc and params else "") + params, ""))
        components = [f'    @JsonProperty("{key}") {java} {field}' for key, field, java, _ in fields]
        out.append(f"public record {name}(\n" + ",\n".join(components) + ") {\n\n")
        out.append(f"    /** A builder for a {{@code {name}}}, every field unset. */\n")
        out.append("    public static Builder builder() {\n        return new Builder();\n    }\n\n")
        out.append(f"    /** Builds a {{@code {name}}}. A field left unset is null, or the zero of a primitive. */\n")
        out.append("    public static final class Builder {\n")
        for _, field, java, _ in fields:
            out.append(f"        private {java} {field};\n")
        out.append("\n        private Builder() {}\n\n")
        for _, field, java, _ in fields:
            out.append(
                f"        public Builder {field}({java} {field}) {{\n"
                f"            this.{field} = {field};\n            return this;\n        }}\n\n"
            )
        names = ", ".join(field for _, field, _, _ in fields)
        out.append(
            f"        public {name} build() {{\n            return new {name}({names});\n        }}\n    }}\n}}\n"
        )
        return "".join(out)

    def enum(self, name: str, schema: dict) -> str:
        out = [BANNER, f"package {PACKAGE};\n\n", "import com.fasterxml.jackson.annotation.JsonProperty;\n\n"]
        if schema.get("description"):
            out.append(javadoc(schema["description"], ""))
        members = ",\n".join(f'    @JsonProperty("{value}")\n    {constant(value)}' for value in schema["enum"])
        out.append(f"public enum {name} {{\n{members}\n}}\n")
        return "".join(out)


def protocol(constants: dict) -> str:
    out = [BANNER, f"package {PACKAGE};\n\n"]
    out.append("/** The values a client has to hold the same as the server. */\npublic final class Protocol {\n")
    out.append("    /** The version of the wire format this client speaks. */\n")
    out.append(f"    public static final int VERSION = {constants['PROTOCOL_VERSION']};\n\n")
    for member, value in constants["Method"].items():
        out.append(f'    public static final String METHOD_{member} = "{value}";\n')
    out.append("\n")
    for member, value in constants["ServerMethod"].items():
        out.append(f'    public static final String SERVER_METHOD_{member} = "{value}";\n')
    out.append("\n    /** The error codes a reply can carry. */\n")
    for member, value in constants["ErrorCode"].items():
        out.append(f"    public static final int ERROR_{member} = {value};\n")
    out.append("\n    private Protocol() {}\n}\n")
    return "".join(out)


def main() -> int:
    document = json.loads(SCHEMA.read_text(encoding="utf-8"))
    generator = Generator(document["$defs"])
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    for name, schema in sorted(document["$defs"].items()):
        if name in SKIPPED:
            continue
        source = generator.enum(name, schema) if "enum" in schema else generator.record(name, schema)
        (OUT / f"{name}.java").write_text(source, encoding="utf-8")
    (OUT / "Protocol.java").write_text(protocol(document["constants"]), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
